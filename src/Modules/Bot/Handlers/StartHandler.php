                [
                    ['text' => "\xF0\x9F\x92\xAC \xDA\xAF\xD9\x81\xD8\xAA\xDA\xAF\xD9\x88\xDB\x8C \xD9\x87\xD9\x88\xD8\xB4", 'callback_data' => 'start_chat']
